// Turns the four e-MENSCR plan files (JSON trees) into src/js/98zo-klang-emenscr-data.js.
// Usage: node tools/build-emenscr-data.js <folder holding ns.json masterplan_mixed.json nr.json plan13.json>
// Each node keeps what the site gives: id, name, parent, whether the site lets a project tick it (_checkenabled), and kpi_id.
// Nodes without an id (109 group labels in masterplan_mixed) get "<parent>~<position>".
const fs = require("fs"), path = require("path");
const dir = process.argv[2] || "C:/Users/Avalant/Downloads";
const FILES = [["ns", "ns.json"], ["mp", "masterplan_mixed.json"], ["nr", "nr.json"], ["p13", "plan13.json"]];
const out = {};
for (const [k, f] of FILES) {
  const t = JSON.parse(fs.readFileSync(path.join(dir, f), "utf8").replace(/^\uFEFF/, "")), rows = [];
  (function w(a, pid) { a.forEach((x, i) => { const id = x.id != null ? String(x.id) : `${pid}~${i + 1}`; rows.push([id, pid, String(x.name || "").trim(), x._checkenabled ? 1 : 0, x.kpi_id ? String(x.kpi_id) : ""]); if (x.children && x.children.length) w(x.children, id); }); })(t, "");
  out[k] = { file: f, rows };
}
const js = "// GENERATED by tools/build-emenscr-data.js from the e-MENSCR plan files; do not edit by hand.\n// rows: [id, parentId, name, selectable(1/0), kpiId]\nconst EM_DATA = " + JSON.stringify(out) + ";\n";
fs.writeFileSync(path.join(__dirname, "..", "src", "js", "98zo-klang-emenscr-data.js"), js);
console.log(Object.entries(out).map(([k, v]) => k + ":" + v.rows.length).join(" "), (js.length / 1e6).toFixed(2) + " MB");
